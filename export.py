def export_gost(papers):
    lines = []
    now_str = datetime.now().strftime("%d.%m.%Y")
    for idx, p in enumerate(papers, 1):
        authors = p.get("authors_str") or "Не указано"
        title = p.get("title") or "Без названия"
        year = str(p.get("year") or "2026")
        doi = p.get("doi")
        journal = p.get("journal")
        journal_part = f" // {journal}." if journal else " // Научная публикация."
        doi_part = f" DOI: https://doi.org/{doi}." if doi else (f" URL: {p['url']} (дата обращения: {now_str})." if p.get("url") else "")
        cites = f" [Цит.: {p.get('cited_by_count', 0)}]" if p.get("cited_by_count") else ""
        lines.append(f"{idx}. {authors} {title}{journal_part} — {year}.{doi_part}{cites}")
    return "\n".join(lines)


def export_markdown_table(papers, cards_map):
    headers = ["#", "Статья / DOI", "Цитат", "Задача", "Метод", "Датасет", "Метрики", "Результат", "Ограничения"]
    sep = ["---"] * len(headers)
    rows = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join(sep) + " |"
    ]
    for idx, p in enumerate(papers, 1):
        pid = p.get("id")
        c = cards_map.get(pid, {})
        doi = p.get("doi")
        doi_link = f"[{p.get('title')[:36]}…](https://doi.org/{doi})" if doi else f"[{p.get('title')[:36]}…]({p.get('url')})"

        clean_row = [
            str(idx),
            doi_link.replace("|", "/"),
            str(p.get("cited_by_count", 0)),
            c.get("task", "не указано").replace("|", "/").replace("\n", " "),
            c.get("method", "не указано").replace("|", "/").replace("\n", " "),
            c.get("dataset", "не указано").replace("|", "/").replace("\n", " "),
            c.get("metrics", "не указано").replace("|", "/").replace("\n", " "),
            c.get("key_result", "не указано").replace("|", "/").replace("\n", " "),
            c.get("limitations", "не указано").replace("|", "/").replace("\n", " "),
        ]
        rows.append("| " + " | ".join(clean_row) + " |")

    return "\n".join(rows)


def export_docx(query, papers, cards_map, author_info=None):
    if Document is None:
        raise RuntimeError("Модуль python-docx не установлен.")

    doc = Document()
    sec = doc.sections[0]
    sec.top_margin, sec.bottom_margin = Inches(0.79), Inches(0.79)
    sec.left_margin, sec.right_margin = Inches(1.18), Inches(0.59)

    norm = doc.styles["Normal"]
    norm.font.name = "Times New Roman"
    norm.font.size = Pt(12)
    try:
        rPr = norm.element.rPr.get_or_add_rFonts()
        rPr.set(qn("w:ascii"), "Times New Roman")
        rPr.set(qn("w:hAnsi"), "Times New Roman")
        rPr.set(qn("w:cs"), "Times New Roman")
    except Exception:
        pass

    author_info = author_info or {}
    ident = [v for v in [author_info.get("university"), author_info.get("name"), author_info.get("field")] if v]
    if ident:
        p = doc.add_paragraph("\n".join(ident))
        p.alignment = 2

    title_p = doc.add_paragraph(f"Сравнительный анализ литературы по теме: {query or 'Исследование'}")
    title_p.paragraph_format.space_before = Pt(12)
    title_p.paragraph_format.space_after = Pt(12)
    for run in title_p.runs:
        run.bold = True
        run.font.size = Pt(14)

    t_p = doc.add_paragraph("Таблица 1 — Сравнительная матрица исследований")
    t_p.paragraph_format.space_after = Pt(6)

    cols = ["#", "Статья / DOI", "Цитат", "Задача", "Метод", "Датасет", "Метрики", "Результат", "Ограничения"]
    table = doc.add_table(rows=1, cols=len(cols))
    table.style = "Table Grid"

    for i, col_name in enumerate(cols):
        cell = table.rows[0].cells[i]
        cell.text = col_name
        for p in cell.paragraphs:
            for r in p.runs:
                r.bold = True

    for idx, paper in enumerate(papers, 1):
        pid = paper.get("id")
        c = cards_map.get(pid, {})
        row = table.add_row().cells
        row[0].text = str(idx)
        doi_s = f"https://doi.org/{paper['doi']}" if paper.get("doi") else (paper.get("url") or "")
        row[1].text = f"{paper.get('title')}\n{doi_s}"
        row[2].text = str(paper.get("cited_by_count", 0))
        row[3].text = c.get("task", "не указано")
        row[4].text = c.get("method", "не указано")
        row[5].text = c.get("dataset", "не указано")
        row[6].text = c.get("metrics", "не указано")
        row[7].text = c.get("key_result", "не указано")
        row[8].text = c.get("limitations", "не указано")

    doc.add_paragraph("\nСписок литературы (ГОСТ 7.0.5-2008):")
    gost_text = export_gost(papers)
    for line in gost_text.split("\n"):
        doc.add_paragraph(line)

    stream = io.BytesIO()
    doc.save(stream)
    return stream.getvalue()
