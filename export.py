def esc_latex(val):
    s = str(val or "")
    repl = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    for k, v in repl.items():
        s = s.replace(k, v)
    return s


def export_bibtex(papers):
    bib_entries = []
    seen_keys = set()
    for idx, p in enumerate(papers, 1):
        key = p.get("citekey") or f"ref{idx}"
        if key in seen_keys:
            key = f"{key}_{idx}"
        seen_keys.add(key)
        entry = get_paper_bibtex(p, citekey=key)
        if entry:
            bib_entries.append(entry)
    return "\n\n".join(bib_entries)


